import { pwsh as q } from './quote.js';

export function renderPwsh({ profiles, hash, bin = 'azure-multiprofile' }) {
  const table = profiles
    .map((p) => `    ${q(p.name)} = @{ az = ${q(p.azureConfigDir)}; azd = ${p.azdConfigDir ? q(p.azdConfigDir) : '$null'} }`)
    .join('\n');

  const oneShots = profiles
    .map((p) => {
      const fns = [`function global:az-${p.name} { __azmp_with ${q(p.name)} 'az' $args }`];
      if (p.azdConfigDir) fns.push(`function global:azd-${p.name} { __azmp_with ${q(p.name)} 'azd' $args }`);
      return fns.join('\n');
    })
    .join('\n');

  return `# azure-multiprofile shell integration (PowerShell). Generated by \`${bin} init pwsh\`.
$env:AZMP_INIT_HASH = ${q(hash)}

$global:__azmp_profiles = @{
${table}
}
$global:__azmp_vars = @('AZURE_CONFIG_DIR', 'AZD_CONFIG_DIR', 'AZMP_PROFILE')

function global:__azmp_set([string]$Name, $Value) {
    if ($null -eq $Value) { Remove-Item "Env:$Name" -ErrorAction SilentlyContinue }
    else { Set-Item "Env:$Name" $Value }
}

function global:__azmp_apply([string]$Name) {
    $p = $global:__azmp_profiles[$Name]
    if (-not $p) {
        [Console]::Error.WriteLine("azmp: unknown profile ""$Name"" (just added it? run: azmp reload)")
        return $false
    }
    __azmp_set 'AZURE_CONFIG_DIR' $p.az
    __azmp_set 'AZD_CONFIG_DIR' $p.azd
    $env:AZMP_PROFILE = $Name
    return $true
}

function global:__azmp_save {
    $global:__azmp_saved = @{}
    foreach ($v in $global:__azmp_vars) {
        $global:__azmp_saved[$v] = [Environment]::GetEnvironmentVariable($v)
    }
}

function global:__azmp_restore {
    if (-not $global:__azmp_saved) { return }
    foreach ($v in $global:__azmp_vars) { __azmp_set $v $global:__azmp_saved[$v] }
}

# Runs one command under a profile without changing the session.
function global:__azmp_with([string]$Name, [string]$Command, [object[]]$Rest) {
    $before = @{}
    foreach ($v in $global:__azmp_vars) { $before[$v] = [Environment]::GetEnvironmentVariable($v) }
    try {
        if (__azmp_apply $Name) { & $Command @Rest }
    } finally {
        foreach ($v in $global:__azmp_vars) { __azmp_set $v $before[$v] }
    }
}

function global:__azmp_find_link {
    $d = (Get-Location -PSProvider FileSystem).ProviderPath
    while ($d) {
        $f = Join-Path $d '.azprofile'
        if (Test-Path -LiteralPath $f -PathType Leaf) {
            $first = Get-Content -LiteralPath $f -TotalCount 1
            $name = if ($first) { ($first.Trim() -split '\\s+')[0] } else { '' }
            if ($name) { return @{ root = $d; name = $name } }
        }
        $parent = Split-Path -Parent $d
        if (-not $parent -or $parent -eq $d) { break }
        $d = $parent
    }
    return $null
}

function global:__azmp_hook {
    if ($env:AZMP_NO_AUTO) { return }
    $here = (Get-Location -PSProvider FileSystem).ProviderPath
    if ($here -eq $global:__azmp_last_pwd) { return }
    $global:__azmp_last_pwd = $here
    if ($env:AZMP_MANUAL) { return }
    $link = __azmp_find_link
    if ($link) {
        if ($link.root -ne $env:AZMP_AUTO_ROOT -or $link.name -ne $env:AZMP_PROFILE) {
            if (-not $env:AZMP_AUTO_ROOT) { __azmp_save }
            if (__azmp_apply $link.name) { $env:AZMP_AUTO_ROOT = $link.root }
        }
    } elseif ($env:AZMP_AUTO_ROOT) {
        __azmp_restore
        Remove-Item Env:AZMP_AUTO_ROOT -ErrorAction SilentlyContinue
    }
}

function global:azmp {
    $sub = if ($args.Count -gt 0) { [string]$args[0] } else { '' }
    if ($sub -eq 'use') {
        if ($args.Count -lt 2) { [Console]::Error.WriteLine('usage: azmp use <profile>'); return }
        if (-not $env:AZMP_AUTO_ROOT -and -not $env:AZMP_MANUAL) { __azmp_save }
        if (__azmp_apply ([string]$args[1])) {
            $env:AZMP_MANUAL = '1'
            Remove-Item Env:AZMP_AUTO_ROOT -ErrorAction SilentlyContinue
        }
    } elseif ($sub -eq 'off') {
        foreach ($v in $global:__azmp_vars + @('AZMP_MANUAL', 'AZMP_AUTO_ROOT')) { __azmp_set $v $null }
        $global:__azmp_last_pwd = $null
        __azmp_hook
    } elseif ($sub -eq 'reload') {
        Invoke-Expression (& ${bin} init pwsh | Out-String)
    } elseif (@('add', 'rename', 'remove', 'rm') -contains $sub) {
        & ${bin} @args
        if ($LASTEXITCODE -eq 0) { Invoke-Expression (& ${bin} init pwsh | Out-String) }
    } elseif ($sub -eq 'link' -or $sub -eq 'unlink') {
        & ${bin} @args
        $global:__azmp_last_pwd = $null
        __azmp_hook
    } else {
        & ${bin} @args
    }
}

function global:azmp_prompt_info {
    if ($env:AZMP_PROFILE) { "az:$($env:AZMP_PROFILE) " } else { '' }
}

${oneShots}

# Prefer LocationChangedAction (PowerShell 7); fall back to wrapping the prompt.
if ($ExecutionContext.InvokeCommand.PSObject.Properties['LocationChangedAction']) {
    $current = $ExecutionContext.InvokeCommand.LocationChangedAction
    if (-not $global:__azmp_hooked) {
        $global:__azmp_prev_lca = $current
        $ExecutionContext.InvokeCommand.LocationChangedAction = {
            param($s, $e)
            if ($global:__azmp_prev_lca) { & $global:__azmp_prev_lca $s $e }
            __azmp_hook
        }
        $global:__azmp_hooked = $true
    }
} elseif (-not $global:__azmp_hooked) {
    $global:__azmp_orig_prompt = $function:prompt
    function global:prompt { __azmp_hook; & $global:__azmp_orig_prompt }
    $global:__azmp_hooked = $true
}
$global:__azmp_last_pwd = $null
__azmp_hook
`;
}
