import { sh as q } from './quote.js';

// Variables whose previous values are saved when a directory link auto-activates
// a profile, and restored when the shell leaves that directory tree.
const SAVED = [
  ['AZURE_CONFIG_DIR', 'az'],
  ['AZD_CONFIG_DIR', 'azd'],
  ['AZMP_PROFILE', 'prof'],
];

/**
 * Shell integration for zsh and bash. Profile directories are baked into the
 * script so `azmp use` and the cd hook never have to start Node.
 */
export function renderPosix(shell, { profiles, hash, bin = 'azure-multiprofile' }) {
  const B = `command ${bin}`;
  const applyCases = profiles
    .map((p) => {
      const azd = p.azdConfigDir ? `export AZD_CONFIG_DIR=${q(p.azdConfigDir)}` : 'unset AZD_CONFIG_DIR';
      return `    ${q(p.name)}) export AZURE_CONFIG_DIR=${q(p.azureConfigDir)}; ${azd} ;;`;
    })
    .join('\n');

  const oneShots = profiles
    .map((p) => {
      const env = [`AZURE_CONFIG_DIR=${q(p.azureConfigDir)}`];
      if (p.azdConfigDir) env.push(`AZD_CONFIG_DIR=${q(p.azdConfigDir)}`);
      env.push(`AZMP_PROFILE=${q(p.name)}`);
      const fns = [`az-${p.name}() { ${env.join(' ')} command az "$@"; }`];
      if (p.azdConfigDir) fns.push(`azd-${p.name}() { ${env.join(' ')} command azd "$@"; }`);
      return fns.join('\n');
    })
    .join('\n');

  const save = SAVED.map(([v, k]) => `  __azmp_s_${k}="\${${v}-}"; __azmp_s_${k}_set="\${${v}+1}"`).join('\n');
  const restore = SAVED.map(
    ([v, k]) => `  if [ -n "$__azmp_s_${k}_set" ]; then export ${v}="$__azmp_s_${k}"; else unset ${v}; fi`,
  ).join('\n');

  const register =
    shell === 'zsh'
      ? `autoload -Uz add-zsh-hook
add-zsh-hook chpwd __azmp_hook`
      : `case ";\${PROMPT_COMMAND[*]:-};" in
  *";__azmp_hook;"*) ;;
  *) PROMPT_COMMAND="__azmp_hook\${PROMPT_COMMAND:+;$PROMPT_COMMAND}" ;;
esac`;

  return `# azure-multiprofile shell integration (${shell}). Generated by \`${bin} init ${shell}\`.
export AZMP_INIT_HASH=${q(hash)}

__azmp_apply() {
  case "$1" in
${applyCases}
    *) printf 'azmp: unknown profile "%s" (just added it? run: azmp reload)\\n' "$1" >&2; return 1 ;;
  esac
  export AZMP_PROFILE="$1"
}

__azmp_save() {
${save}
}

__azmp_restore() {
${restore}
}

# Walks up from $PWD looking for a .azprofile file.
__azmp_find_link() {
  local d="$PWD"
  while [ -n "$d" ]; do
    if [ -f "$d/.azprofile" ]; then
      __azmp_link_root="$d"
      __azmp_link_name=""
      read -r __azmp_link_name _ < "$d/.azprofile" || true
      __azmp_link_name="\${__azmp_link_name%$'\\r'}"
      [ -n "$__azmp_link_name" ] && return 0
    fi
    [ "$d" = "/" ] && break
    d="\${d%/*}"
    [ -z "$d" ] && d="/"
  done
  return 1
}

__azmp_hook() {
  [ -n "\${AZMP_NO_AUTO-}" ] && return 0
  [ "$PWD" = "\${__azmp_last_pwd-}" ] && return 0
  __azmp_last_pwd="$PWD"
  [ -n "\${AZMP_MANUAL-}" ] && return 0
  if __azmp_find_link; then
    if [ "$__azmp_link_root" != "\${AZMP_AUTO_ROOT-}" ] || [ "$__azmp_link_name" != "\${AZMP_PROFILE-}" ]; then
      [ -z "\${AZMP_AUTO_ROOT-}" ] && __azmp_save
      __azmp_apply "$__azmp_link_name" && export AZMP_AUTO_ROOT="$__azmp_link_root"
    fi
  elif [ -n "\${AZMP_AUTO_ROOT-}" ]; then
    __azmp_restore
    unset AZMP_AUTO_ROOT
  fi
  return 0
}

azmp() {
  case "\${1-}" in
    use)
      if [ -z "\${2-}" ]; then echo "usage: azmp use <profile>" >&2; return 2; fi
      if [ -z "\${AZMP_AUTO_ROOT-}" ] && [ -z "\${AZMP_MANUAL-}" ]; then __azmp_save; fi
      __azmp_apply "$2" || return 1
      export AZMP_MANUAL=1
      unset AZMP_AUTO_ROOT
      ;;
    off)
      unset AZURE_CONFIG_DIR AZD_CONFIG_DIR AZMP_PROFILE AZMP_MANUAL AZMP_AUTO_ROOT
      __azmp_last_pwd=""
      __azmp_hook
      ;;
    reload)
      eval "$(${B} init ${shell})"
      ;;
    add|rename|remove|rm)
      ${B} "$@" || return $?
      eval "$(${B} init ${shell})"
      ;;
    link|unlink)
      ${B} "$@" || return $?
      __azmp_last_pwd=""
      __azmp_hook
      ;;
    *)
      ${B} "$@"
      ;;
  esac
}

# For PS1: prints "az:<profile> " when a profile is active.
azmp_prompt_info() {
  [ -n "\${AZMP_PROFILE-}" ] && printf 'az:%s ' "$AZMP_PROFILE"
  return 0
}

${oneShots}

${register}
__azmp_hook
`;
}
