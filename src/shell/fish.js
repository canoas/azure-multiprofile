import { fish as q } from './quote.js';

const SAVED = [
  ['AZURE_CONFIG_DIR', 'az'],
  ['AZD_CONFIG_DIR', 'azd'],
  ['AZMP_PROFILE', 'prof'],
];

export function renderFish({ profiles, hash, bin = 'azure-multiprofile' }) {
  const B = `command ${bin}`;
  const applyCases = profiles
    .map((p) => {
      const azd = p.azdConfigDir ? `set -gx AZD_CONFIG_DIR ${q(p.azdConfigDir)}` : 'set -e AZD_CONFIG_DIR';
      return `        case ${q(p.name)}\n            set -gx AZURE_CONFIG_DIR ${q(p.azureConfigDir)}\n            ${azd}`;
    })
    .join('\n');

  const oneShots = profiles
    .map((p) => {
      const env = [`AZURE_CONFIG_DIR=${q(p.azureConfigDir)}`];
      if (p.azdConfigDir) env.push(`AZD_CONFIG_DIR=${q(p.azdConfigDir)}`);
      env.push(`AZMP_PROFILE=${q(p.name)}`);
      const fns = [`function az-${p.name}\n    env ${env.join(' ')} az $argv\nend`];
      if (p.azdConfigDir) fns.push(`function azd-${p.name}\n    env ${env.join(' ')} azd $argv\nend`);
      return fns.join('\n');
    })
    .join('\n');

  const save = SAVED.map(
    ([v, k]) =>
      `    if set -q ${v}\n        set -g __azmp_s_${k} $${v}; set -g __azmp_s_${k}_set 1\n    else\n        set -g __azmp_s_${k}_set ''\n    end`,
  ).join('\n');
  const restore = SAVED.map(
    ([v, k]) => `    if test -n "$__azmp_s_${k}_set"\n        set -gx ${v} $__azmp_s_${k}\n    else\n        set -e ${v}\n    end`,
  ).join('\n');

  return `# azure-multiprofile shell integration (fish). Generated by \`${bin} init fish\`.
set -gx AZMP_INIT_HASH ${q(hash)}

function __azmp_apply
    switch $argv[1]
${applyCases}
        case '*'
            printf 'azmp: unknown profile "%s" (just added it? run: azmp reload)\\n' $argv[1] >&2
            return 1
    end
    set -gx AZMP_PROFILE $argv[1]
    # set -e on an unset variable leaves status 4 behind; callers chain on success.
    return 0
end

function __azmp_save
${save}
end

function __azmp_restore
${restore}
    return 0
end

function __azmp_find_link
    set -l d $PWD
    while test -n "$d"
        if test -f "$d/.azprofile"
            set -g __azmp_link_root $d
            set -l first (string split -n ' ' -- (head -n 1 "$d/.azprofile" | string trim))
            set -g __azmp_link_name $first[1]
            test -n "$__azmp_link_name"; and return 0
        end
        test "$d" = /; and break
        set d (dirname -- $d)
    end
    return 1
end

function __azmp_hook --on-variable PWD
    set -q AZMP_NO_AUTO; and return 0
    test "$PWD" = "$__azmp_last_pwd"; and return 0
    set -g __azmp_last_pwd $PWD
    set -q AZMP_MANUAL; and return 0
    if __azmp_find_link
        if test "$__azmp_link_root" != "$AZMP_AUTO_ROOT"; or test "$__azmp_link_name" != "$AZMP_PROFILE"
            set -q AZMP_AUTO_ROOT; or __azmp_save
            __azmp_apply $__azmp_link_name; and set -gx AZMP_AUTO_ROOT $__azmp_link_root
        end
    else if set -q AZMP_AUTO_ROOT
        __azmp_restore
        set -e AZMP_AUTO_ROOT
    end
    return 0
end

function azmp
    switch "$argv[1]"
        case use
            if test -z "$argv[2]"
                echo "usage: azmp use <profile>" >&2
                return 2
            end
            if not set -q AZMP_AUTO_ROOT; and not set -q AZMP_MANUAL
                __azmp_save
            end
            __azmp_apply $argv[2]; or return 1
            set -gx AZMP_MANUAL 1
            set -e AZMP_AUTO_ROOT
            return 0
        case off
            for v in AZURE_CONFIG_DIR AZD_CONFIG_DIR AZMP_PROFILE AZMP_MANUAL AZMP_AUTO_ROOT
                set -e $v
            end
            set -g __azmp_last_pwd ''
            __azmp_hook
        case reload
            ${B} init fish | source
        case add rename remove rm
            ${B} $argv; or return $status
            ${B} init fish | source
        case link unlink
            ${B} $argv; or return $status
            set -g __azmp_last_pwd ''
            __azmp_hook
        case '*'
            ${B} $argv
    end
end

function azmp_prompt_info
    set -q AZMP_PROFILE; and printf 'az:%s ' $AZMP_PROFILE
    return 0
end

${oneShots}

set -g __azmp_last_pwd ''
__azmp_hook
`;
}
